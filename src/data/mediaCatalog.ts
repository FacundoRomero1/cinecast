function loadInitialCatalog(): MediaCatalog {
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('cinecast_catalog_v7');
      if (saved) {
        const parsed = JSON.parse(saved);
        if (parsed && Array.isArray(parsed.movies) && parsed.movies.length >= 10) {
          return parsed;
        }
      }
    } catch (_) {}
  }
  return {
    movies: [...sampleMovies],
    shows: [],
    lastUpdated: new Date().toISOString(),
  };
}

